// Copies the tree-sitter runtime and the prebuilt grammar WASMs from node_modules
// (pinned devDependencies) into grammars/, and records what was copied in grammars/VERSIONS.
// Run after changing a grammar or web-tree-sitter version: `npm run grammars`.
import console from 'node:console';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { Language, LANGUAGE_VERSION, MIN_COMPATIBLE_VERSION, Parser } from 'web-tree-sitter';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'grammars');
const pkgDir = (name) => join(root, 'node_modules', name);
const versionOf = (name) =>
  JSON.parse(readFileSync(join(pkgDir(name), 'package.json'), 'utf8')).version;

const RUNTIME = { pkg: 'web-tree-sitter', from: 'web-tree-sitter.wasm', to: 'tree-sitter.wasm' };
const GRAMMARS = [
  { pkg: 'tree-sitter-typescript', from: 'tree-sitter-typescript.wasm' },
  { pkg: 'tree-sitter-typescript', from: 'tree-sitter-tsx.wasm' },
  { pkg: 'tree-sitter-javascript', from: 'tree-sitter-javascript.wasm' },
  { pkg: 'tree-sitter-python', from: 'tree-sitter-python.wasm' },
  { pkg: 'tree-sitter-go', from: 'tree-sitter-go.wasm' },
];

mkdirSync(out, { recursive: true });
copyFileSync(join(pkgDir(RUNTIME.pkg), RUNTIME.from), join(out, RUNTIME.to));
await Parser.init({ wasmBinary: readFileSync(join(out, RUNTIME.to)) });

const lines = [
  '# Generated by scripts/fetch-grammars.mjs from the pinned packages in package.json. Do not edit.',
  '# file\tpackage@version\tABI',
  `${RUNTIME.to}\t${RUNTIME.pkg}@${versionOf(RUNTIME.pkg)}\taccepts ${MIN_COMPATIBLE_VERSION}-${LANGUAGE_VERSION}`,
];
let failed = false;
for (const g of GRAMMARS) {
  const dest = join(out, g.from);
  copyFileSync(join(pkgDir(g.pkg), g.from), dest);
  const abi = (await Language.load(readFileSync(dest))).abiVersion;
  if (abi < MIN_COMPATIBLE_VERSION || abi > LANGUAGE_VERSION) {
    console.error(`${g.from}: ABI ${abi} outside ${MIN_COMPATIBLE_VERSION}-${LANGUAGE_VERSION}`);
    failed = true;
  }
  lines.push(`${g.from}\t${g.pkg}@${versionOf(g.pkg)}\t${abi}`);
}
writeFileSync(join(out, 'VERSIONS'), lines.join('\n') + '\n');
console.log(lines.slice(2).join('\n'));
if (failed) process.exit(1);
